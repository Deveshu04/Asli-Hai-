DEFAULT_LANGUAGE = "hi"


def greeting(language: str, kind: str, **names: str) -> str:
    return LANGUAGES.get(language, LANGUAGES[DEFAULT_LANGUAGE])[kind].format(**names)


def in_script(text: str, language: str) -> bool:
    script = LANGUAGES[language]["script"]
    return script is None or bool(re.search(f"[{script}]", text))
